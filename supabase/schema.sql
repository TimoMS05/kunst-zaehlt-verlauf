-- So benutzen: In Supabase links "SQL Editor" öffnen, diese Datei
-- komplett hineinkopieren und auf "Run" klicken.
--
-- Wer darf was? (Row Level Security)
--  - Besucher (anon):   aktive Stationen lesen, einen Besuch eintragen.
--                       Sie können KEINE Besuche lesen.
--  - Admins:            alles lesen, Stationen anlegen und ändern.
--                       Admin ist, wessen E-Mail in der Tabelle "admins" steht.
--  - Löschen über die Website ist nicht möglich (nur hier im SQL Editor).
-- =====================================================================


-- ---------- Tabellen ----------

create table if not exists public.stationen (
  id        integer generated by default as identity primary key,
  name      text not null check (char_length(name) between 1 and 80),
  text      text not null default '' check (char_length(text) <= 3000),
  aktiv     boolean not null default true,     -- false = archiviert
  erstellt  timestamptz not null default now()
);

create table if not exists public.besuche (
  id          bigint generated always as identity primary key,
  station_id  integer not null references public.stationen (id),
  zeit        timestamptz not null default now(),   -- setzt immer der Server
  besucher_id uuid,                                 -- nur mit Einwilligung (Cookie), sonst leer
  sprache     text not null default '--' check (sprache ~ '^([a-z]{2}|--)$')
);

create index if not exists besuche_besucher_zeit on public.besuche (besucher_id, zeit);
create index if not exists besuche_zeit on public.besuche (zeit);

create table if not exists public.admins (
  email text primary key
);


-- ---------- Hilfsfunktion: Ist die angemeldete Person Admin? ----------

create or replace function public.ist_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;


-- ---------- Regeln (Row Level Security) ----------

alter table public.stationen enable row level security;
alter table public.besuche   enable row level security;
alter table public.admins    enable row level security;   -- keine Regel = kein Zugriff über die Website

drop policy if exists stationen_lesen   on public.stationen;
drop policy if exists stationen_anlegen on public.stationen;
drop policy if exists stationen_aendern on public.stationen;
drop policy if exists besuche_eintragen on public.besuche;
drop policy if exists besuche_lesen     on public.besuche;

create policy stationen_lesen on public.stationen
  for select using (aktiv or public.ist_admin());

create policy stationen_anlegen on public.stationen
  for insert to authenticated with check (public.ist_admin());

create policy stationen_aendern on public.stationen
  for update to authenticated using (public.ist_admin()) with check (public.ist_admin());

create policy besuche_eintragen on public.besuche
  for insert to anon, authenticated
  with check (exists (select 1 from public.stationen s where s.id = station_id and s.aktiv));

create policy besuche_lesen on public.besuche
  for select to authenticated using (public.ist_admin());

-- Besucher dürfen nur diese drei Spalten setzen. Zeitpunkt und Nummer
-- vergibt die Datenbank selbst, damit niemand Zeiten fälschen kann.
revoke insert, update, delete on public.besuche from anon, authenticated;
grant insert (station_id, besucher_id, sprache) on public.besuche to anon, authenticated;
grant select on public.besuche to authenticated;


-- ---------- Zahl für den ESP32 (und andere öffentliche Anzeigen) ----------
-- Gibt nur die Gesamtzahl der Scans zurück, keine einzelnen Besuche.

create or replace function public.anzahl_scans()
returns bigint
language sql stable security definer
set search_path = public
as $$
  select count(*) from public.besuche;
$$;

revoke all on function public.anzahl_scans() from public;
grant execute on function public.anzahl_scans() to anon, authenticated;


